-- Specs for timers.lua and format.lua (pure logic, clock driven by hand).
local DIR = debug.getinfo(1, "S").source:sub(2):match("(.*[/\\])") or "./"
package.path = DIR .. "?.lua;" .. package.path

local T = require("timers")
local F = require("format")

describe("Stopwatch", function()
    it("measures wall-clock time, not ticks", function()
        local sw = T.newStopwatch()
        sw:start(1000)
        assert.are.equal(0, sw:elapsed(1000))
        assert.are.equal(12.5, sw:elapsed(1012.5))
        -- nobody looked for an hour (repaints missed, device asleep)
        assert.are.equal(3600, sw:elapsed(4600))
    end)

    it("pauses and resumes", function()
        local sw = T.newStopwatch()
        sw:start(0); sw:pause(10)
        assert.are.equal(10, sw:elapsed(500))
        sw:start(600)
        assert.are.equal(15, sw:elapsed(605))
        assert.is_true(sw:isRunning())
    end)

    it("never goes below the accumulated time if the clock goes back", function()
        local sw = T.newStopwatch()
        sw:start(0); sw:pause(30); sw:start(100)
        assert.are.equal(30, sw:elapsed(50))
    end)

    it("records laps with splits and finds the fastest and slowest", function()
        local sw = T.newStopwatch()
        sw:start(0)
        sw:lap(60); sw:lap(115); sw:lap(185)
        assert.are.equal(3, #sw.laps)
        assert.are.same({ n = 2, total = 115, split = 55 }, sw.laps[2])
        local best, worst = sw:lapExtremes()
        assert.are.equal(2, best)
        assert.are.equal(3, worst)
        sw:reset()
        assert.are.equal(0, #sw.laps)
        assert.is_true(sw:isZero())
    end)
end)

describe("Countdown", function()
    it("rings once at its end instant", function()
        local c = T.newCountdown(1, "Kitchen", 300)
        c:start(1000)
        assert.is_nil(c:check(1299.9))
        assert.are.equal(0.5, c:remainingAt(1299.5))
        local ev = c:check(1300)
        assert.are.same({ kind = "timer", id = 1, name = "Kitchen", at = 1300 }, ev)
        assert.is_nil(c:check(1301))
        assert.are.equal("done", c.state)
    end)

    it("reports the real finish time after a sleep gap", function()
        local c = T.newCountdown(1, "Tea", 180)
        c:start(0)
        assert.is_nil(c:check(10))
        -- the reader slept from t=10 to t=1000: first check after resume
        local ev = c:check(1000)
        assert.are.equal(180, ev.at)
        assert.are.equal(180, c.done_at)
    end)

    it("pauses, resumes and restarts", function()
        local c = T.newCountdown(1, "x", 60)
        c:start(0); c:pause(20)
        assert.are.equal(40, c:remainingAt(9999))
        c:start(100)
        assert.are.equal(140, c:nextDeadline())
        c:check(140)
        c:start(200)          -- restart after done: full duration again
        assert.are.equal(260, c:nextDeadline())
        c:reset()
        assert.are.equal(60, c:remainingAt(0))
        assert.is_nil(c:nextDeadline())
    end)
end)

describe("Interval", function()
    it("lays out prep, work and rest phases, no rest after the last round", function()
        local iv = T.newInterval(30, 10, 3, 5)
        local list, total = iv:phases()
        assert.are.equal(6, #list)  -- prep, w1, r1, w2, r2, w3
        assert.are.equal(5 + 30 * 3 + 10 * 2, total)
        assert.are.equal("work", list[#list].kind)
        local i, p, left = iv:phaseAt(20)
        assert.are.equal(2, i); assert.are.equal("work", p.kind); assert.are.equal(15, left)
        i, p, left = iv:phaseAt(36)
        assert.are.equal(3, i); assert.are.equal("rest", p.kind); assert.are.equal(9, left)
        assert.is_nil(iv:phaseAt(total))
    end)

    it("emits each phase boundary with its wall-clock instant", function()
        local iv = T.newInterval(30, 10, 2, 0)
        iv:start(100)
        assert.are.same({}, iv:check(110))
        local ev = iv:check(135)
        assert.are.equal(1, #ev)
        assert.are.equal("rest", ev[1].phase.kind)
        assert.are.equal(130, ev[1].at)
        assert.are.equal(140, iv:nextDeadline())
    end)

    it("catches up on every boundary missed during sleep, then ends", function()
        local iv = T.newInterval(30, 10, 2, 5)
        iv:start(0)
        local ev = iv:check(10000)
        -- work1 at 5, rest1 at 35, work2 at 45, end at 75
        assert.are.equal(4, #ev)
        assert.are.equal(5, ev[1].at)
        assert.are.equal("interval", ev[4].kind)
        assert.are.equal(75, ev[4].at)
        assert.are.equal("done", iv.state)
        assert.are.same({}, iv:check(10001))
        assert.is_nil(iv:nextDeadline())
    end)

    it("pauses without losing its place", function()
        local iv = T.newInterval(30, 10, 2, 0)
        iv:start(0); iv:pause(20)
        assert.are.equal(20, iv:elapsed(500))
        iv:start(500)
        assert.are.equal(510, iv:nextDeadline())
    end)
end)

describe("Model", function()
    it("collects events oldest first and finds the next deadline", function()
        local m = T.newModel()
        local a = m:addTimer("A", 60)
        local b = m:addTimer("B", 30)
        a:start(0); b:start(0)
        assert.are.equal(30, m:nextDeadline())
        assert.is_true(m:alarmRunning())
        local ev = m:check(100)
        assert.are.equal(2, #ev)
        assert.are.equal("B", ev[1].name)
        assert.is_false(m:alarmRunning())
    end)

    it("caps the number of timers", function()
        local m = T.newModel()
        for i = 1, T.MAX_TIMERS do assert.is_truthy(m:addTimer("t" .. i, 60)) end
        assert.is_nil(m:addTimer("extra", 60))
        m:removeTimer(m.timers[1].id)
        assert.are.equal(T.MAX_TIMERS - 1, #m.timers)
    end)

    it("round-trips through serialize/load, running clocks included", function()
        local m = T.newModel()
        m.stopwatch:start(10); m.stopwatch:lap(20)
        local t = m:addTimer("Pasta", 600); t:start(0)
        m.interval:configure(20, 10, 4, 0); m.interval:start(0)
        local m2 = T.load(m:serialize())
        assert.are.equal(m.stopwatch:elapsed(50), m2.stopwatch:elapsed(50))
        assert.are.equal(1, #m2.stopwatch.laps)
        assert.are.equal(600, m2.timers[1]:nextDeadline())
        assert.are.equal(m.interval:nextDeadline(), m2.interval:nextDeadline())
        assert.is_truthy(m2:addTimer("new", 60).id > t.id)
    end)

    it("survives garbage in the saved state", function()
        local m = T.load({ timers = { { duration = "x" }, 5, { duration = 60, state = "weird" } }, stopwatch = 3 })
        assert.are.equal(1, #m.timers)
        assert.are.equal("idle", m.timers[1].state)
        assert.is_truthy(T.load(nil))
    end)
end)

describe("sleep gap", function()
    it("tells what rang on time from what finished during a sleep", function()
        local m = T.newModel()
        m:addTimer("Eggs", 300):start(0)
        m:addTimer("Bread", 1200):start(0)
        m:addTimer("Roast", 3600):start(0)
        -- alarm for Eggs fired on time
        local late, fresh = T.splitLate(m:check(300.05), 300.05, 5)
        assert.are.equal(0, #late); assert.are.equal(1, #fresh)
        -- then the reader slept from t=400 to t=2000: Bread rang at 1200
        late, fresh = T.splitLate(m:check(2000), 2000, 5)
        assert.are.equal(1, #late); assert.are.equal(0, #fresh)
        assert.are.equal("Bread", late[1].name)
        assert.are.equal(1200, late[1].at)
        assert.are.equal(3600, m:nextDeadline())
        assert.are.equal(1600, m.timers[3]:remainingAt(2000))
    end)
end)

describe("format", function()
    it("formats counting up and down", function()
        assert.are.equal("00:59", F.up(59.9))
        assert.are.equal("01:00", F.up(60))
        assert.are.equal("1:00:05", F.up(3605))
        assert.are.equal("00:01", F.down(0.2))
        assert.are.equal("00:00", F.down(0))
        assert.are.equal("05:00", F.down(300))
        assert.are.equal("01:23.4", F.tenths(83.47))
    end)

    it("parses typed durations", function()
        assert.are.equal(300, F.parse("5"))
        assert.are.equal(90, F.parse("1:30"))
        assert.are.equal(3600, F.parse("1:00:00"))
        assert.are.equal(90, F.parse("90s"))
        assert.are.equal(5400, F.parse("1h30"))
        assert.are.equal(5400, F.parse("1 h 30 min"))
        assert.are.equal(150, F.parse("2,5"))
        assert.is_nil(F.parse("0"))
        assert.is_nil(F.parse("1:75"))
        assert.is_nil(F.parse("abc"))
        assert.is_nil(F.parse(""))
    end)

    it("labels durations", function()
        assert.are.equal("5 min", F.short(300))
        assert.are.equal("1 h 30 min", F.short(5400))
        assert.are.equal("1 min 30 s", F.short(90))
        assert.are.equal("0 s", F.short(0))
    end)
end)
